#!/usr/bin/env bash
# Prepare a private bootstrap archive from the running database/application host.
# Usage: sudo bash export-app-node.sh 172.31.21.52
set -Eeuo pipefail
[[ $EUID -eq 0 ]] || { echo 'Run this script with sudo.' >&2; exit 1; }
database_ip=${1:?Provide this instance private IPv4 address}
[[ "$database_ip" =~ ^[0-9.]+$ ]] || exit 1
ip -4 -o addr show | awk '{split($4, address, "/"); print address[1]}' | grep -Fxq "$database_ip" || {
    echo 'The database address must belong to this host.' >&2; exit 1;
}
docker port fullstack-postgres 5432/tcp | grep -Fxq "$database_ip:5432" || {
    echo 'Enable private database publishing before exporting the application.' >&2; exit 1;
}
exec 9>/var/lock/fullstack-deploy.lock
flock -w 120 9 || { echo 'Another deployment is running.' >&2; exit 1; }
curl -fsS --max-time 15 http://127.0.0.1/api/products >/dev/null
revision=$(cat /var/www/fullstack-lab/release.txt)
[[ "$revision" =~ ^[0-9a-f]{40}$ ]] || { echo 'A deployed release revision is required.' >&2; exit 1; }

umask 077
staging=$(mktemp -d /var/tmp/fullstack-node-export.XXXXXX)
cleanup() {
    if [[ "$staging" == /var/tmp/fullstack-node-export.* && -d "$staging" ]]; then
        rm -rf -- "$staging"
    fi
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
mkdir "$staging/bootstrap"
cp /opt/fullstack-lab/app.jar "$staging/bootstrap/app.jar"
cp -a /var/www/fullstack-lab "$staging/bootstrap/www"
cp /etc/nginx/nginx.conf "$staging/bootstrap/nginx.conf"
[[ -z $(find "$staging/bootstrap" -type l -print -quit) ]] || {
    echo 'Symlinks are not supported in the bootstrap archive.' >&2; exit 1;
}

# This root-owned file was generated by install.sh. Never print its contents.
# shellcheck disable=SC1091
source /etc/fullstack-lab/postgres.env
[[ "$POSTGRES_DB" == products_db && "$POSTGRES_USER" == fullstack && "$POSTGRES_PASSWORD" =~ ^[0-9a-f]{64}$ ]] || {
    echo 'Unexpected database configuration; inspect it privately.' >&2; exit 1;
}
cat > "$staging/bootstrap/app.env" <<EOF
DB_URL=jdbc:postgresql://$database_ip:5432/products_db
DB_USER=fullstack
DB_PASSWORD=$POSTGRES_PASSWORD
SERVER_ADDRESS=127.0.0.1
PORT=8080
SERVER_FORWARD_HEADERS_STRATEGY=framework
SPRING_H2_CONSOLE_ENABLED=false
SPRING_DATASOURCE_HIKARI_MAXIMUM_POOL_SIZE=5
APP_SEED=false
SPRING_JPA_HIBERNATE_DDL_AUTO=validate
EOF
unset POSTGRES_PASSWORD
tar -czf "$staging/node-bootstrap.tar.gz" -C "$staging" bootstrap
transfer_dir=/home/ec2-user/fullstack-node-transfer
[[ ! -L "$transfer_dir" ]] || { echo 'Transfer directory must not be a symlink.' >&2; exit 1; }
install -d -o ec2-user -g ec2-user -m 700 "$transfer_dir"
install -o ec2-user -g ec2-user -m 600 "$staging/node-bootstrap.tar.gz" "$transfer_dir/node-bootstrap.tar.gz"
(cd "$transfer_dir" && sha256sum node-bootstrap.tar.gz > node-bootstrap.sha256)
chown ec2-user:ec2-user "$transfer_dir/node-bootstrap.sha256"
chmod 600 "$transfer_dir/node-bootstrap.sha256"
printf 'APP NODE EXPORT READY\nRevision: %s\nArchive: %s/node-bootstrap.tar.gz\n' "$revision" "$transfer_dir"
echo 'This archive contains database credentials. Transfer over SSH, then remove both copies.'
